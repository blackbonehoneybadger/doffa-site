import { test } from "node:test";
import assert from "node:assert/strict";
import { ссылкаВИгру, ECOSYSTEM } from "../app/config/ecosystem";

// Формат обязан совпадать с игрой (public/telegram.mjs) слово в слово: бот
// разбирает ровно две формы, ?start=ref_DF-000000 и ?startapp. Ссылка с любым
// третьим видом уводит игрока мимо приглашения молча — заметить это можно
// только по пустому списку приглашённых через месяц.
const БОТ = "doffadrakabot";

test("код дополняется нулями до шести знаков, как в игре", () => {
  assert.equal(ссылкаВИгру(БОТ, "DF-7"), `https://t.me/${БОТ}?start=ref_DF-000007`);
  assert.equal(ссылкаВИгру(БОТ, "DF-123456"), `https://t.me/${БОТ}?start=ref_DF-123456`);
});

test("дефис в коде необязателен, регистр не важен", () => {
  assert.equal(ссылкаВИгру(БОТ, "df42"), `https://t.me/${БОТ}?start=ref_DF-000042`);
  assert.equal(ссылкаВИгру(БОТ, "  DF-42  "), `https://t.me/${БОТ}?start=ref_DF-000042`);
});

test("код длиннее шести знаков не режется", () => {
  assert.equal(ссылкаВИгру(БОТ, "DF-1234567"), `https://t.me/${БОТ}?start=ref_DF-1234567`);
});

test("без кода — обычный вход в игру, а не ссылка на чужое приглашение", () => {
  assert.equal(ссылкаВИгру(БОТ, null), `https://t.me/${БОТ}?startapp`);
  assert.equal(ссылкаВИгру(БОТ, ""), `https://t.me/${БОТ}?startapp`);
  assert.equal(ссылкаВИгру(БОТ, "   "), `https://t.me/${БОТ}?startapp`);
});

test("мусор вместо кода не подставляется в ссылку", () => {
  // Приглашение привязывается к аккаунту навсегда, переиграть его нечем.
  // Поэтому непонятный код — это обычный вход, а не попытка угадать.
  for (const мусор of ["ABC", "DF-", "DF-12a", "12345", "ref_DF-1", "DF-1;rm -rf"]) {
    assert.equal(ссылкаВИгру(БОТ, мусор), `https://t.me/${БОТ}?startapp`, `код ${мусор}`);
  }
});

test("недопустимое имя бота откатывается к настоящему", () => {
  // Пустая или битая переменная окружения не должна уводить людей в никуда.
  for (const имя of [null, "", "ab", "-плохо-", "имя_бота"]) {
    assert.ok(ссылкаВИгру(имя, "DF-1").startsWith(`https://t.me/${БОТ}?`), `имя ${имя}`);
  }
});

test("своё имя бота используется, если оно годное", () => {
  assert.equal(ссылкаВИгру("doffa_test_bot", "DF-9"), "https://t.me/doffa_test_bot?start=ref_DF-000009");
});

test("сайт ведёт по реферальной ссылке владельца слово в слово", () => {
  // Ссылку прислал владелец. Если она разойдётся с тем, что собирает сайт,
  // приглашённые перестанут засчитываться — и заметить это можно будет только
  // по пустому списку приглашённых через месяц.
  assert.equal(ECOSYSTEM.game.telegramUrl, "https://t.me/doffadrakabot?start=ref_DF-000001");
  assert.equal(ECOSYSTEM.game.referralCode, "DF-000001");
  assert.equal(ECOSYSTEM.game.botUsername, БОТ);
});
