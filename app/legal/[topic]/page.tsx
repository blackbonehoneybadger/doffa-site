const TOPICS = Object.keys(CONTENT) as Topic[];

export function generateStaticParams() {
  return TOPICS.map((topic) => ({ topic }));
}

export async function generateMetadata(
  { params }: { params: Promise<{ topic: string }> },
): Promise<Metadata> {
  const { topic } = await params;
  const c = CONTENT[topic as Topic];
  if (!c) return { title: "Юридическая информация — DOFFA" };
  return { title: `${c.title} — DOFFA`, description: c.intro, alternates: { canonical: `/legal/${topic}` } };
}

